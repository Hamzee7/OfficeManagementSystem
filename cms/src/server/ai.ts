import { type DB, newId } from "./db";
import { HttpError, type AuthContext } from "./auth";
import { audit } from "./audit";
import { loadOrg } from "./org";
import { getAiProvider, tokens } from "@/lib/ai";
import { requireComplaint } from "./complaints";

function requireAi(db: DB, ctx: AuthContext) {
  if (!ctx.perms.has("ai.use")) throw new HttpError(403, "You do not have permission to use AI assistance.");
  if (!loadOrg(db, ctx.orgId).aiEnabled) throw new HttpError(409, "AI assistance is turned off for this organization. Use the manual tools instead.");
}

function save(db: DB, ctx: AuthContext, complaintId: string, kind: string, payload: unknown, rationale: string): string {
  const id = newId();
  db.prepare("INSERT INTO ai_recommendations (id, org_id, complaint_id, kind, payload, rationale, provider, created_at) VALUES (?,?,?,?,?,?,?,?)").run(id, ctx.orgId, complaintId, kind, JSON.stringify(payload), rationale, getAiProvider().name, Date.now());
  return id;
}

/** Suggestions for a handler: summary, draft reply, similar complaints and knowledge articles. Nothing is sent or changed. */
export function assist(db: DB, ctx: AuthContext, complaintId: string, kind: "summary" | "draft_update" | "draft_resolution" | "draft_request_info" | "duplicates" | "knowledge") {
  requireAi(db, ctx);
  const c = requireComplaint(db, ctx, complaintId);
  const ai = getAiProvider();
  const org = loadOrg(db, ctx.orgId);
  let result: any;
  if (kind === "summary") {
    const ev = db.prepare("SELECT created_at, actor_name, actor_kind, body FROM complaint_events WHERE complaint_id = ? AND body IS NOT NULL ORDER BY created_at, rowid").all(complaintId) as any[];
    result = { text: ai.summarize([{ when: c.created_at, who: c.complainant_name ?? "Complainant", text: `${c.title}. ${c.description}` }, ...ev.map((e) => ({ when: e.created_at, who: e.actor_name ?? e.actor_kind, text: e.body }))]), sentiment: ai.sentiment(c.description) };
  } else if (kind.startsWith("draft_")) {
    const k = ({ draft_update: "update", draft_resolution: "resolution", draft_request_info: "request_info" } as const)[kind as "draft_update" | "draft_resolution" | "draft_request_info"];
    result = { text: ai.draftResponse(k, { name: c.complainant_name ?? undefined, ref: c.ref, org: org.name, detail: k === "resolution" ? c.resolution_summary ?? undefined : undefined }), note: "Draft only. Review and edit before sending." };
  } else if (kind === "duplicates") {
    const others = db.prepare("SELECT id, ref, title, description FROM complaints WHERE org_id = ? AND id != ? ORDER BY created_at DESC LIMIT 500").all(ctx.orgId, complaintId) as any[];
    result = { matches: ai.findDuplicates(`${c.title} ${c.description}`, others.map((o) => ({ id: o.id, ref: o.ref, text: `${o.title} ${o.description}` }))), note: "Possible matches only. Link records manually; nothing is merged." };
  } else {
    const q = new Set(tokens(`${c.title} ${c.description}`));
    const arts = db.prepare("SELECT id, title, body FROM kb_articles WHERE org_id = ? AND published = 1").all(ctx.orgId) as any[];
    const scored = arts.map((a) => { const t = new Set(tokens(`${a.title} ${a.body}`)); let n = 0; for (const w of q) if (t.has(w)) n++; return { id: a.id, title: a.title, score: n }; }).filter((a) => a.score >= 2).sort((a, b) => b.score - a.score).slice(0, 5);
    result = { articles: scored, note: "Suggested reading. Verify against current policy before relying on it." };
  }
  const id = save(db, ctx, complaintId, kind, result, `Generated by ${ai.name}`);
  audit(db, { orgId: ctx.orgId, actorId: ctx.userId, actorLabel: ctx.email, action: "ai.used", entityType: "complaint", entityId: complaintId, data: { kind } });
  return { id, provider: ai.name, ...result };
}

export function decideRecommendation(db: DB, ctx: AuthContext, id: string, accept: boolean): void {
  requireAi(db, ctx);
  const r = db.prepare("SELECT * FROM ai_recommendations WHERE id = ? AND org_id = ?").get(id, ctx.orgId) as any;
  if (!r) throw new HttpError(404, "Recommendation not found.");
  requireComplaint(db, ctx, r.complaint_id);
  db.prepare("UPDATE ai_recommendations SET status = ?, decided_by = ?, decided_at = ? WHERE id = ? AND status = 'pending'").run(accept ? "accepted" : "rejected", ctx.userId, Date.now(), id);
  audit(db, { orgId: ctx.orgId, actorId: ctx.userId, actorLabel: ctx.email, action: accept ? "ai.accepted" : "ai.rejected", entityType: "ai_recommendation", entityId: id, data: { kind: r.kind } });
}
