const slug = (s: string) => s.replace(/\s+/g, "-");

export const StatusBadge = ({ status }: { status: string }) => <span className={`badge st-${slug(status)}`}>{status}</span>;
export const PriorityBadge = ({ priority }: { priority: string }) => <span className={`badge pr-${priority}`}>{priority}</span>;

export function SlaBadge({ sla }: { sla: SlaSnapshot }) {
  const text =
    sla.state === "Breached" ? `Breached by ${formatDuration(-sla.remainingMinutes)}`
    : sla.state === "Completed" ? "Completed"
    : sla.state === "Paused" ? `Paused · ${formatDuration(sla.remainingMinutes)} left`
    : `${sla.state} · ${formatDuration(sla.remainingMinutes)} left`;
  return <span className={`badge sla-${slug(sla.state)}`}>{text}</span>;
}

export function SlaMeter({ sla }: { sla: SlaSnapshot }) {
  const pct = Math.min(100, sla.consumedPct);
  const cls = sla.state === "Breached" ? "bad" : sla.state === "At Risk" ? "warn" : "";
  return (
    <div className={`meter ${cls}`} role="img" aria-label={`${sla.consumedPct}% of the SLA used`}>
      <i style={{ width: `${pct}%` }} />
    </div>
  );
}

export function Empty({ title, children, action }: { title: string; children?: ReactNode; action?: ReactNode }) {
  return (
    <div className="empty">
      <strong>{title}</strong>
      {children && <p>{children}</p>}
      {action}
    </div>
  );
}

export function fmtDateTime(ms: number | null | undefined, tz = "UTC"): string {
  if (!ms) return "–";
  return new Intl.DateTimeFormat("en-GB", { timeZone: tz, day: "2-digit", month: "short", year: "numeric", hour: "2-digit", minute: "2-digit" }).format(new Date(ms));
}
export function fmtDate(ms: number | null | undefined, tz = "UTC"): string {
  if (!ms) return "–";
  return new Intl.DateTimeFormat("en-GB", { timeZone: tz, day: "2-digit", month: "short", year: "numeric" }).format(new Date(ms));
}
export function ago(ms: number, now = Date.now()): string {
  const m = Math.round((now - ms) / 60000);
  if (m < 1) return "just now";
  if (m < 60) return `${m}m ago`;
  const h = Math.round(m / 60);
  if (h < 48) return `${h}h ago`;
  return `${Math.round(h / 24)}d ago`;
}
export const minutesLabel = (m: number | null) => (m == null ? "n/a" : formatDuration(m));
